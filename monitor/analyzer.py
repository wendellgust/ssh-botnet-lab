def main():
    parser = argparse.ArgumentParser(
        description="Lab Log Analyzer — detection rules for SSH botnet lab"
    )
    parser.add_argument("--live",   action="store_true", help="Real-time monitoring")
    parser.add_argument("--report", action="store_true", help="Print summary report")
    parser.add_argument("--rules",  action="store_true", help="List detection rules")
    args = parser.parse_args()

    if args.rules:
        list_rules()
        return

    if args.live:
        live_monitor()
        return

    alerts = run_analysis(verbose=True)

    if args.report:
        print_report(alerts)


if __name__ == "__main__":
    main()
