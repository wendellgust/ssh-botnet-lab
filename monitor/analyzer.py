def run_analysis(verbose: bool = True) -> list[Alert]:
    print("\n[analyzer] Loading logs...")
    auth_events = parse_auth_log(AUTH_LOG)
    honeypot_events = parse_honeypot_log(HONEYPOT_LOG)

    print(f"[analyzer] Parsed {len(auth_events)} auth events, "
          f"{len(honeypot_events)} honeypot events")

    all_alerts = []
    rules = [
        ("SSH-001 Brute Force",        lambda: rule_ssh_brute_force(auth_events)),
        ("SSH-002 Password Spray",      lambda: rule_password_spray(auth_events)),
        ("SSH-003 Successful BF Login", lambda: rule_successful_auth_from_suspicious(auth_events)),
        ("LATERAL-001 East-West SSH",   lambda: rule_lateral_movement(auth_events)),
        ("HONEYPOT-001 Honeypot Hit",   lambda: rule_honeypot_hit(honeypot_events)),
        ("C2-001 Beaconing",            lambda: rule_c2_beaconing(honeypot_events)),
    ]

    for rule_name, rule_fn in rules:
        alerts = rule_fn()
        if alerts and verbose:
            for a in alerts:
                print(a)
        all_alerts.extend(alerts)

    return all_alerts


def print_report(alerts: list[Alert]):
    print("\n" + "=" * 60)
    print(" DETECTION REPORT SUMMARY")
    print("=" * 60)

    by_sev = Counter(a.severity for a in alerts)
    print(f"\n  Total alerts:    {len(alerts)}")
    for sev in [CRITICAL, HIGH, MEDIUM, LOW, INFO]:
        count = by_sev.get(sev, 0)
        if count:
            print(f"  {sev:10s}:  {count}")

    if not alerts:
        print("\n  No alerts generated.")
        print("  Run the simulator first: docker exec attacker python3 /lab/simulator.py botnet")
    else:
        print("\n  Triggered rules:")
        for a in alerts:
            print(f"    [{a.severity:8s}] {a.rule_id} — {a.title}")

    print("\n" + "=" * 60)


def live_monitor():
    """Watch logs in real time and alert on new events."""
    print("[analyzer] Live monitoring mode — press Ctrl+C to stop\n")
    seen_lines = set()
    while True:
        alerts = run_analysis(verbose=False)
        for a in alerts:
            key = f"{a.rule_id}:{a.source_ip}"
            if key not in seen_lines:
                print(a)
                seen_lines.add(key)
        time.sleep(5)


def list_rules():
    print("\n Detection Rules Catalog\n")
    print(f"  {'ID':<16} {'SEVERITY':<10} {'NAME':<35} {'DETECTS'}")
    print("  " + "-" * 90)
    for r in RULES_CATALOG:
        print(f"  {r['id']:<16} {r['severity']:<10} {r['name']:<35} {r['detects']}")
    print()


